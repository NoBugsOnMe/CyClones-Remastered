void World::buildKeepsake() {
    if (keepsake_.count > 0) return;   // the renderer keeps the voxels for the whole session
    VoxelModel m;
    auto put = [&](int x, int y, int z, int c) { m.vox.push_back({(int16_t)x, (int16_t)y, (int16_t)z, (uint8_t)c}); };

    // The frame: 4 voxels wide all round, mitred at the corners. Model x runs left to right as
    // seen from the room, y up from the bottom of the plate, z out from the wall.
    const int W = kPhotoW + 8, H = kPhotoH + 8, B = 4, Y0 = 9, X0 = -W / 2;
    const int depth[B] = {2, 3, 3, 2};
    // Dark wood with a gilt liner next to the picture.
    const uint8_t lit[B] = {72, 76, 74, 86};      // top and left: catching the light
    const uint8_t shade[B] = {69, 72, 70, 81};    // bottom and right
    for (int y = 0; y < H; ++y)
        for (int x = 0; x < W; ++x) {
            int top = H - 1 - y, right = W - 1 - x;
            int d = std::min(std::min(x, right), std::min(y, top));
            if (d >= B) {
                put(X0 + x, Y0 + y, 0, kPhoto[(top - B) * kPhotoW + (x - B)]);
                continue;
            }
            // The nearer side decides; top and bottom take the diagonal (the mitre).
            bool vertical = std::min(y, top) <= std::min(x, right);
            bool light = vertical ? top < y : x < right;
            for (int z = 0; z < depth[d]; ++z) put(X0 + x, Y0 + y, z, light ? lit[d] : shade[d]);
        }

    // The plate: brass, dark lettering, a screw at each end.
    struct Glyph { int w = 0, h = 0, left = 0, adv = 3; const uint8_t* p = nullptr; };
    auto glyph = [&](char ch) {
        Glyph g;
        int i = data_->hd.find("c" + std::to_string((int)(unsigned char)ch));
        if (i < 0 || data_->hd.size(i) < 8) return g;
        const uint8_t* d = data_->hd.data(i);
        int w = d[0] | d[1] << 8, h = d[2] | d[3] << 8;
        if (w <= 0 || h <= 0 || (size_t)(8 + w * h) > data_->hd.size(i)) return g;
        g.w = w; g.h = std::min(h, 5); g.p = d + 8;
        int lo = w, hi = -1;
        for (int yy = 0; yy < g.h; ++yy)
            for (int xx = 0; xx < w; ++xx)
                if (g.p[yy * w + xx] && g.p[yy * w + xx] != 2) { lo = std::min(lo, xx); hi = std::max(hi, xx); }
        if (hi >= 0) { g.left = lo; g.adv = hi - lo + 2; }
        return g;
    };
    std::string text = kKeepsakeText;
    int textW = 0;
    for (char ch : text) textW += glyph(ch).adv;
    textW -= 1;   // no gap after the last letter
    const int PW = textW + 6, PH = 7, PX0 = -PW / 2;
    std::vector<uint8_t> ink((size_t)PW * PH, 0);
    int cx = 3;
    for (char ch : text) {
        Glyph g = glyph(ch);
        if (g.p)
            for (int yy = 0; yy < g.h; ++yy)
                for (int xx = g.left; xx < g.w; ++xx) {
                    uint8_t v = g.p[yy * g.w + xx];
                    int px = cx + xx - g.left;
                    if (v && v != 2 && px < PW) ink[(size_t)(1 + yy) * PW + px] = 1;
                }
        cx += g.adv;
    }
    for (int y = 0; y < PH; ++y)
        for (int x = 0; x < PW; ++x) {
            int row = PH - 1 - y;   // ink rows run top down
            bool edge = x == 0 || y == 0 || x == PW - 1 || y == PH - 1;
            bool screw = (x == 1 || x == PW - 2) && row == 3;
            if (screw) { for (int z = 0; z < 3; ++z) put(PX0 + x, y, z, z == 2 ? 24 : 18); continue; }
            uint8_t c = ink[(size_t)row * PW + x] ? 68 : edge ? (y == 0 || x == PW - 1 ? 78 : 88) : 86;
            put(PX0 + x, y, 0, c);
            put(PX0 + x, y, 1, c);
        }
    keepsake_ = renderer_->addModel(still(m));
}

void World::addKeepsakeDraw(Scene& sc, const Camera& cam) const {
    if (!keepsakeHere_ || keepsake_.count <= 0) return;
    float dx = cam.x - kWallX, dz = cam.z - kWallZ;
    if (dz > 0 || dx * dx + dz * dz > 2000.0f * 2000.0f) return;   // behind the wall, or far off
    ModelDraw d;
    d.range = keepsake_;
    d.pos[0] = kWallX;
    d.pos[1] = kBaseY;
    d.pos[2] = kWallZ - 0.02f;
    yawMatrix(0, d.rot);   // facing north, into the room
    // Lit like the wall it hangs on (the wall's own light byte, not the room's floor), a shade
    // darker so the photograph's white doesn't glare.
    int cell = (int)(kWallZ / kCellSize) * kGrid + (int)(kWallX / kCellSize);
    d.light = (float)(int8_t)level_->north.light[cell] + 4;
    sc.models.push_back(d);
}
